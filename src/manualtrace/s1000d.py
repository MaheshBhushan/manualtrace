"""Map extracted records to S1000D-style XML data modules.

Element names follow S1000D Issue 5.0 (dmodule / identAndStatusSection / content with
procedure, description and illustratedPartsCatalog). This is an S1000D-*style* subset: it is
checked against the local schema `s1000d_subset.xsd` (next to this module), not the full
S1000D schema set. Provenance (source document, page, bounding box) is carried on every
content element via attributes in the `urn:manualtrace:provenance` namespace.

One document produces three data modules:
- infoCode 012 "General warnings and cautions" (descriptive) with every WARNING/CAUTION/NOTE;
- infoCode 300 procedural module containing each extracted procedure as a mainProcedure
  step group, with the warnings/cautions found on the same pages in its safetyRqmts;
- infoCode 941 illustrated-parts-catalog-style module with one catalogSeqNumber per part.
"""

from __future__ import annotations

import datetime as dt
from pathlib import Path

from lxml import etree

from .schemas import Admonition, ExtractionResult, Provenance
from .sources import Source

PROV_NS = "urn:manualtrace:provenance"
P = f"{{{PROV_NS}}}"
NSMAP = {"mt": PROV_NS}
MODEL_IDENT = "MANUALTRACE"

INFO_CODES = {"warnings": ("012", "General warnings and cautions"),
              "procedures": ("300", "Procedures"),
              "parts": ("941", "Illustrated parts data")}


def _sub(parent, tag, text=None, **attrs):
    el = etree.SubElement(parent, tag, {k: v for k, v in attrs.items() if v is not None})
    if text is not None:
        el.text = text
    return el


def _prov(el, provs: list[Provenance]) -> None:
    first = provs[0]
    el.set(P + "doc", first.doc_id)
    el.set(P + "page", str(first.page))
    el.set(P + "bbox", first.bbox.as_attr())
    if len(provs) > 1:
        # Continuations onto further page regions: "page:l,t,r,b;page:l,t,r,b"
        el.set(P + "more", ";".join(f"{p.page}:{p.bbox.as_attr()}" for p in provs[1:]))


def dm_code(source: Source, info_code: str) -> dict[str, str]:
    return {
        "modelIdentCode": MODEL_IDENT,
        "systemDiffCode": "A",
        "systemCode": source.system_code,
        "subSystemCode": "0",
        "subSubSystemCode": "0",
        "assyCode": "00",
        "disassyCode": "00",
        "disassyCodeVariant": "A",
        "infoCode": info_code,
        "infoCodeVariant": "A",
        "itemLocationCode": "D",
    }


def dm_filename(code: dict[str, str]) -> str:
    c = code
    return (
        f"DMC-{c['modelIdentCode']}-{c['systemDiffCode']}-{c['systemCode']}-"
        f"{c['subSystemCode']}{c['subSubSystemCode']}-{c['assyCode']}-"
        f"{c['disassyCode']}{c['disassyCodeVariant']}-{c['infoCode']}"
        f"{c['infoCodeVariant']}-{c['itemLocationCode']}_EN-US.xml"
    )


def _dmodule(source: Source, result: ExtractionResult, kind: str, issue_date: dt.date):
    info_code, info_name = INFO_CODES[kind]
    root = etree.Element("dmodule", nsmap=NSMAP)
    ident = _sub(root, "identAndStatusSection")
    addr = _sub(ident, "dmAddress")
    dm_ident = _sub(addr, "dmIdent")
    code = dm_code(source, info_code)
    _sub(dm_ident, "dmCode", **code)
    _sub(dm_ident, "language", languageIsoCode="en", countryIsoCode="US")
    _sub(dm_ident, "issueInfo", issueNumber="001", inWork="00")
    items = _sub(addr, "dmAddressItems")
    _sub(items, "issueDate", year=f"{issue_date.year:04d}", month=f"{issue_date.month:02d}",
         day=f"{issue_date.day:02d}")
    title = _sub(items, "dmTitle")
    _sub(title, "techName", source.title)
    _sub(title, "infoName", info_name)
    status = _sub(ident, "dmStatus", issueType="new")
    _sub(status, "security", securityClassification="01")
    _sub(status, "responsiblePartnerCompany", enterpriseCode="00000")
    _sub(status, "originator", enterpriseCode="00000")
    _sub(status, "applic").append(_display_text("All"))
    _sub(status, "brexDmRef").append(_dm_ref(source, "022"))
    _sub(status, "qualityAssurance").append(etree.Element("unverified"))
    _sub(status, "remarks").append(
        _simple_para(f"Generated by manualtrace ({result.extractor}) from {source.url}")
    )
    content = _sub(root, "content")
    return root, content, code


def _display_text(text: str):
    dt_el = etree.Element("displayText")
    _sub(dt_el, "simplePara", text)
    return dt_el


def _simple_para(text: str):
    el = etree.Element("simplePara")
    el.text = text
    return el


def _dm_ref(source: Source, info_code: str):
    ref = etree.Element("dmRef")
    ref_ident = _sub(ref, "dmRefIdent")
    _sub(ref_ident, "dmCode", **dm_code(source, info_code))
    return ref


def _admonition(parent, adm: Admonition):
    if adm.kind == "note":
        el = _sub(parent, "note", id=adm.id)
        _sub(el, "notePara", adm.text)
    else:
        el = _sub(parent, adm.kind, id=adm.id)
        _sub(el, "warningAndCautionPara", adm.text)
    _prov(el, adm.provenance)
    return el


def _warnings_dm(source, result, issue_date):
    root, content, code = _dmodule(source, result, "warnings", issue_date)
    desc = _sub(content, "description")
    lp = _sub(desc, "levelledPara")
    _sub(lp, "title", "Warnings, cautions and notes")
    for adm in result.admonitions:
        _admonition(lp, adm)
    if not result.admonitions:
        _sub(lp, "para", "No warnings, cautions or notes were extracted.")
    return root, code


def _procedures_dm(source, result, issue_date):
    root, content, code = _dmodule(source, result, "procedures", issue_date)
    proc = _sub(content, "procedure")
    prelim = _sub(proc, "preliminaryRqmts")
    _sub(_sub(prelim, "reqCondGroup"), "noConds")
    _sub(_sub(prelim, "reqSupportEquips"), "noSupportEquips")
    _sub(_sub(prelim, "reqSupplies"), "noSupplies")
    _sub(_sub(prelim, "reqSpares"), "noSpares")
    proc_pages = {p.page for pr in result.procedures for p in pr.provenance}
    related = [a for a in result.admonitions
               if a.kind != "note" and {p.page for p in a.provenance} & proc_pages]
    safety = _sub(prelim, "reqSafety")
    if related:
        group = _sub(safety, "safetyRqmts")
        for adm in related:
            el = _admonition(group, adm)
            el.set("id", f"{adm.id}-ref")
    else:
        _sub(safety, "noSafety")
    main = _sub(proc, "mainProcedure")
    for pr in result.procedures:
        group = _sub(main, "proceduralStep", id=pr.id)
        _prov(group, pr.provenance)
        _sub(group, "title", pr.title)
        for i, step in enumerate(pr.steps, 1):
            st = _sub(group, "proceduralStep", id=f"{pr.id}-s{i}")
            st.set(P + "label", step.number)
            _prov(st, step.provenance)
            _sub(st, "para", step.text)
    if not result.procedures:
        _sub(_sub(main, "proceduralStep"), "para", "No procedures were extracted.")
    _sub(_sub(proc, "closeRqmts"), "reqCondGroup").append(etree.Element("noConds"))
    return root, code


def _parts_dm(source, result, issue_date):
    root, content, code = _dmodule(source, result, "parts", issue_date)
    ipc = _sub(content, "illustratedPartsCatalog")
    for n, part in enumerate(result.parts, 1):
        csn = _sub(ipc, "catalogSeqNumber", id=part.id, catalogSeqNumberValue=f"{n:03d}",
                   item=part.item)
        _prov(csn, part.provenance)
        isn = _sub(csn, "itemSeqNumber", itemSeqNumberValue="00A")
        if part.quantity:
            _sub(isn, "quantityPerNextHigherAssy", part.quantity)
        _sub(isn, "partRef", partNumberValue=part.part_number or "",
             manufacturerCodeValue=part.cage or "")
        ident = _sub(isn, "partIdentSegment")
        _sub(ident, "descrForPart", part.description)
        loc = _sub(isn, "partLocationSegment")
        if part.nsn:
            _sub(loc, "nationalStockNumber", nsn=part.nsn)
        if part.unit:
            _sub(loc, "unitOfIssue", part.unit)
        if part.smr:
            _sub(loc, "sourceMaintRecoverability", part.smr)
    return root, code


BUILDERS = {"warnings": _warnings_dm, "procedures": _procedures_dm, "parts": _parts_dm}


def build_modules(result: ExtractionResult, source: Source,
                  issue_date: dt.date | None = None) -> dict[str, etree._Element]:
    issue_date = issue_date or dt.date.today()
    out = {}
    for kind, builder in BUILDERS.items():
        root, code = builder(source, result, issue_date)
        out[dm_filename(code)] = root
    return out


def schema() -> etree.XMLSchema:
    path = Path(__file__).with_name("s1000d_subset.xsd")
    return etree.XMLSchema(etree.parse(str(path)))


def export_document(result: ExtractionResult, source: Source, out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    xsd = schema()
    written = []
    for name, root in build_modules(result, source).items():
        xsd.assertValid(root)
        path = out_dir / name
        path.write_bytes(etree.tostring(root, xml_declaration=True, encoding="UTF-8",
                                        pretty_print=True))
        written.append(path)
    return written
